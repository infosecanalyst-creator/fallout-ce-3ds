#!/usr/bin/env python3
"""Build the in-game manual (C++ header) and the Markdown manual for each game
from docs/manual-source.txt. Lines starting with [1] or [2] belong to one game."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'docs', 'manual-source.txt'), encoding='utf-8').read().splitlines()

def lines_for(game):
    out = []
    for line in src:
        if line.startswith('[1]') or line.startswith('[2]'):
            if line[1] != str(game):
                continue
            line = line[3:]
        out.append(line)
    return out

def c_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

for game, folder, title in [(1, 'fallout1', 'Fallout'), (2, 'fallout2', 'Fallout 2')]:
    lines = lines_for(game)
    for l in lines:
        if any(ord(c) > 126 for c in l):
            sys.exit('non-ASCII text in manual: ' + l)
    h = os.path.join(root, folder, 'src', 'platform', 'ctr', 'ctr_manual_text.h')
    with open(h, 'w', newline='\n') as f:
        f.write('// Generated by tools/gen_manual.py from docs/manual-source.txt. Do not edit.\n')
        f.write('#ifndef CTR_MANUAL_TEXT_H\n#define CTR_MANUAL_TEXT_H\n\n')
        f.write('static const char* const kManualTitle = "%s for New 3DS";\n' % title)
        f.write('static const char* const kManualLines[] = {\n')
        for l in lines:
            f.write('    "%s",\n' % c_escape(l))
        f.write('};\n\n#endif\n')
    md = os.path.join(root, 'docs', 'MANUAL-%s.md' % ('FALLOUT1' if game == 1 else 'FALLOUT2'))
    with open(md, 'w', newline='\n') as f:
        f.write('# %s for New 3DS: manual\n\n' % title)
        f.write('*This is the same manual the game shows on the console (Select on any menu, Select+Start on the map).*\n\n')
        intable = False
        inlist = False
        for l in lines:
            if l.startswith('| '):
                k, _, v = l[2:].partition(' | ')
                if not intable:
                    f.write('| Input | What it does |\n|---|---|\n')
                    intable = True
                f.write('| %s | %s |\n' % (k, v))
                continue
            if intable:
                f.write('\n')
                intable = False
            if inlist and (l.startswith('#')):
                f.write('\n')
                inlist = False
            if l.startswith('# '):
                f.write('#' + l + '\n\n')
            elif l.startswith('## '):
                f.write('#' + l + '\n\n')
            elif l == '':
                if inlist:
                    f.write('\n')
                    inlist = False
                continue
            elif l.startswith('- ') or (len(l) > 2 and l[0].isdigit() and l[1] == '.'):
                f.write(l + '\n')
                inlist = True
                continue
            else:
                if inlist:
                    f.write('\n')
                    inlist = False
                f.write(l + '\n\n')
    print('wrote', h, md)
